/**
 * Bootstrap a full testnet environment:
 *   fee account F (friendbot), admin / platform / treasury / anchor accounts (sponsored by F),
 *   a test "USDC" asset + its Stellar Asset Contract, treasury funding, and the asset-trail
 *   contract deployed with (admin, platform, USDC SAC).
 * Writes everything to backend/.env.testnet.
 *
 *   npm run bootstrap:testnet [-- path/to/asset_trail.wasm]
 */
import { randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Address, Asset, Keypair, Networks, Operation, rpc, scValToNative } from '@stellar/stellar-sdk';
import { createSponsoredAccount } from '../src/stellar/accounts.js';
import { addr } from '../src/stellar/scval.js';
import { Submitter } from '../src/stellar/submitter.js';

const RPC = process.env.STELLAR_RPC_URL ?? 'https://soroban-testnet.stellar.org';
const PASSPHRASE = Networks.TESTNET;
// fileURLToPath, not URL.pathname: on Windows the pathname is "/C:/…", which fs can't open.
const wasmPath = process.argv[2] ?? fileURLToPath(new URL('../../artifacts/asset_trail.wasm', import.meta.url));

const server = new rpc.Server(RPC);
const log = (...a: unknown[]) => console.log('•', ...a);

const fee = Keypair.random();
const issuer = Keypair.random();
const admin = Keypair.random();
const platform = Keypair.random();
const treasury = Keypair.random();
const anchor = Keypair.random();

log('funding fee account and USDC issuer with friendbot');
await Promise.all([server.fundAddress(fee.publicKey()), server.fundAddress(issuer.publicKey())]);

const sub = new Submitter(server, PASSPHRASE, fee);
const usdc = new Asset('USDC', issuer.publicKey());

log('creating sponsored admin, platform, treasury (+USDC trustline) and mock-anchor accounts');
await createSponsoredAccount(sub, admin);
await createSponsoredAccount(sub, platform);
await createSponsoredAccount(sub, treasury, usdc);
await createSponsoredAccount(sub, anchor, usdc);

log('issuing 100,000 test USDC to treasury');
await sub.classic([Operation.payment({ source: issuer.publicKey(), destination: treasury.publicKey(), asset: usdc, amount: '100000' })], [issuer]);

log('deploying the USDC Stellar Asset Contract');
const sacId = usdc.contractId(PASSPHRASE);
try {
  await sub.hostFromOp(Operation.createStellarAssetContract({ asset: usdc }));
} catch (e) {
  if (!/exist/i.test(String((e as Error).message))) throw e;
}

log(`uploading ${wasmPath}`);
const wasm = readFileSync(wasmPath);
const upload = await sub.hostFromOp(Operation.uploadContractWasm({ wasm }));
const wasmHash = Buffer.from(scValToNative(upload.returnValue!) as Uint8Array);
log('wasm hash', wasmHash.toString('hex'));

log('deploying asset-trail');
const deployed = await sub.hostFromOp(
  Operation.createCustomContract({
    address: Address.fromString(fee.publicKey()),
    wasmHash,
    salt: randomBytes(32),
    constructorArgs: [addr(admin.publicKey()), addr(platform.publicKey()), addr(sacId)],
  }),
);
const contractId = Address.fromScVal(deployed.returnValue!).toString();
log('contract', contractId);

const env = `# Generated by scripts/bootstrap-testnet.ts on ${new Date().toISOString()} — TESTNET ONLY
STELLAR_RPC_URL=${RPC}
STELLAR_NETWORK_PASSPHRASE=${PASSPHRASE}
CONTRACT_ID=${contractId}
PAY_ASSET=USDC:${issuer.publicKey()}
USDC_SAC=${sacId}
USDC_ISSUER_SECRET=${issuer.secret()}
FEE_SECRET=${fee.secret()}
ADMIN_SECRET=${admin.secret()}
PLATFORM_SECRET=${platform.secret()}
TREASURY_SECRET=${treasury.secret()}
MOCK_ANCHOR_ACCOUNT=${anchor.publicKey()}
MOCK_ANCHOR_SECRET=${anchor.secret()}
RECEIVER_KEY_ENCRYPTION_KEY=${randomBytes(32).toString('base64')}
JWT_SECRET=${randomBytes(32).toString('base64url')}
`;
const out = fileURLToPath(new URL('../.env.testnet', import.meta.url));
writeFileSync(out, env, { mode: 0o600 });
log(`wrote ${out}`);
